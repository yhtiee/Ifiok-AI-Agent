import { randomUUID } from "node:crypto";
import type { BrowserContext } from "@playwright/test";
import { createServerClient } from "@supabase/ssr";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import type { Database } from "../../lib/supabase/types";

// Test helpers that talk to the real Supabase project. They need SUPABASE_SERVICE_ROLE_KEY
// (loaded from .env / .env.local by playwright.config.ts); specs skip themselves without it.

const url = process.env.NEXT_PUBLIC_SUPABASE_URL ?? "";
const publishableKey = process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ?? "";
const secretKey = process.env.SUPABASE_SERVICE_ROLE_KEY ?? "";

export const hasSupabaseAdmin = Boolean(url && publishableKey && secretKey && !url.includes("placeholder"));

export function adminClient(): SupabaseClient<Database> {
  return createClient<Database>(url, secretKey, { auth: { persistSession: false, autoRefreshToken: false } });
}

/** A fresh test email. Uses example.com, which never receives mail. */
export function testEmail() {
  return `e2e-${randomUUID()}@example.com`;
}

/** A fresh test user, optionally with a password. */
export async function createTestUser(opts: { password?: string } = {}) {
  const email = testEmail();
  const { data, error } = await adminClient().auth.admin.createUser({
    email,
    email_confirm: true,
    ...(opts.password ? { password: opts.password } : {}),
  });
  if (error || !data.user) throw new Error(`createUser failed: ${error?.message}`);
  return { id: data.user.id, email };
}

/** The id of an account created through the UI, found by signing in with its password. */
export async function userIdFor(email: string, password: string) {
  const client = createClient<Database>(url, publishableKey, { auth: { persistSession: false } });
  const { data, error } = await client.auth.signInWithPassword({ email, password });
  if (error || !data.user) return null;
  return data.user.id;
}

export async function deleteTestUser(id: string) {
  await adminClient().auth.admin.deleteUser(id);
}

/**
 * Signs the browser in as `email` exactly as the app's verifyCode action does: a one-time code
 * (generated by the admin API instead of an email) is verified through @supabase/ssr, and the
 * session cookies it writes are copied into the browser context.
 */
export async function signInAs(context: BrowserContext, email: string, baseURL: string) {
  const { data, error } = await adminClient().auth.admin.generateLink({ type: "magiclink", email });
  const code = data?.properties?.email_otp;
  if (error || !code) throw new Error(`generateLink failed: ${error?.message}`);

  const jar = new Map<string, string>();
  const supabase = createServerClient<Database>(url, publishableKey, {
    cookies: {
      getAll: () => [...jar].map(([name, value]) => ({ name, value })),
      setAll: (cookies) => cookies.forEach((c) => jar.set(c.name, c.value)),
    },
  });
  const verified = await supabase.auth.verifyOtp({ email, token: code, type: "email" });
  if (verified.error) throw new Error(`verifyOtp failed: ${verified.error.message}`);

  const { hostname } = new URL(baseURL);
  await context.addCookies(
    [...jar].map(([name, value]) => ({ name, value, domain: hostname, path: "/", sameSite: "Lax" as const })),
  );
}

/** Year and month that make someone exactly 18 this month: still treated as under 18 (Q16). */
export function birthMonthTurning18Now(now = new Date()) {
  const lagos = new Intl.DateTimeFormat("en-GB", { timeZone: "Africa/Lagos", year: "numeric", month: "numeric" })
    .formatToParts(now)
    .reduce<Record<string, string>>((acc, p) => ({ ...acc, [p.type]: p.value }), {});
  return { year: Number(lagos.year) - 18, month: Number(lagos.month) };
}

/**
 * A test user who has finished onboarding: adult, consented (current version), at a university
 * (by short name, e.g. "UNIUYO"), at a level. Skips the onboarding screens for feature tests.
 */
export async function createOnboardedUser(opts: { university: string; level: number }) {
  const user = await createTestUser();
  const db = adminClient();
  const { data: uni } = await db.from("universities").select("id").eq("short_name", opts.university).single();
  await db
    .from("profiles")
    .update({
      is_adult: true,
      birth_year: 1999,
      birth_month: 4,
      university_id: uni!.id,
      level: opts.level,
      daily_minutes: 30,
      onboarded_at: new Date().toISOString(),
      first_name: "Test",
      last_name: opts.university,
    })
    .eq("id", user.id);
  const { CONSENT_VERSION } = await import("../../lib/auth/consent");
  await db
    .from("consents")
    .insert(
      ["terms", "privacy", "ai_disclosure"].map((kind) => ({ user_id: user.id, kind, version: CONSENT_VERSION })),
    );
  return user;
}
